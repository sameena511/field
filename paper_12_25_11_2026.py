def validate_map(frame, allow_review=True):
    if frame.rid.duplicated().any() or set(frame.rid) != set(records.rid):
        raise ValueError("Expected exactly one decision per source ID.")
    allowed = set(catalog) | {"OUT"} | ({"REVIEW"} if allow_review else set())
    if not frame.target.isin(allowed).all() or not frame.op.isin(ops).all():
        raise ValueError("Unknown target or conversion.")
    if not frame.target.isin(["OUT", "REVIEW"]).equals(frame.op.eq("none")):
        raise ValueError("OUT and REVIEW require conversion 'none', and mapped rows require a conversion.")
    return frame

