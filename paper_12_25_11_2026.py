def normalise(value, op, seconds):
    if not math.isfinite(seconds) or seconds <= 0:
        raise ValueError("A finite, positive interval is required.")
    if pd.isna(value):
        return np.nan
    if op == "identity": return value
    if op == "bytes_to_bps": return 8 * value / seconds
    if op == "count_to_pps": return value / seconds
    if op == "bytesps_to_bps": return 8 * value
    if op == "percent_to_fraction": return value / 100
    raise ValueError(f"Unsupported conversion: {op}")

def build_report(mapping, observations):
    x = observations.merge(mapping[["rid", "target", "op"]], on="rid", how="left", validate="many_to_one")
    if x.target.isna().any():
        raise ValueError("At least one input field lacks a mapping decision.")
    x = x.loc[~x.target.isin(["OUT", "REVIEW"])].copy()
    seconds = (x.end - x.start).dt.total_seconds()
    x["value"] = [normalise(v, op, s) for v, op, s in zip(x.native, x.op, seconds)]
    # Keep one cell, its provenance and multiplicity. Collisions cannot produce a trusted number.
    result = (x.groupby(key, sort=False, as_index=False, dropna=False)
                .agg(value=("value", "first"), n_sources=("rid", "size"), source=("rid", "first")))
    result.loc[result.n_sources.gt(1), "value"] = np.nan
    return result

def reconcile(expected, actual):
    if expected.n_sources.ne(1).any():
        raise ValueError("Reference mappings collide. Resolve grain or select an authoritative series.")
    joined = expected.merge(actual, on=key, how="outer", suffixes=("_expected", "_actual"),
                            indicator=True, validate="one_to_one")
    both = joined._merge.eq("both")
    collision = joined.n_sources_actual.fillna(0).gt(1)
    comparable = both & ~collision
    same_value = np.isclose(joined.value_expected, joined.value_actual,
                            rtol=1e-9, atol=1e-10, equal_nan=True)
    joined["status"] = np.select(
        [collision, joined._merge.eq("left_only"), joined._merge.eq("right_only"), comparable & ~same_value],
        ["collision", "missing", "unexpected", "wrong value"], default="match")
    return joined

