def synthetic_native(row, index, window_index):
    # Different amplitudes per series make swapped or scaled series distinguishable.
    activity = (index + 3) * 71 + window_index * 9 + (window_index % 4) * 27
    if row.unit == "byte":
        return 10_000 * activity
    if row.unit == "bit/s":
        return 20_000 * activity
    if row.unit == "byte/s":
        return 125_000_000 if "capacity" in row.metric else 1_000 * activity
    if row.unit == "dBm":
        return round(-12.0 + (index % 5) * 0.5 + 0.2 * math.sin(window_index), 3)
    if row.unit == "percent":
        return 45 + (activity % 46)
    if row.unit in {"flag", "flag-like number", "fraction"}:
        return float(window_index != 5)
    if row.rid in {"A05", "D05", "D06", "D07", "D08", "E03", "E04", "F08"}:
        return (index + window_index) % 13
    return activity

