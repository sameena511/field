def words(identifier):
    identifier = re.sub(r"([a-z0-9])([A-Z])", r"\1 \2", identifier)
    identifier = re.sub(r"([A-Z])([A-Z][a-z])", r"\1 \2", identifier)
    return set(re.findall(r"[a-z0-9]+", identifier.lower()))

def choose_op(base, unit, stat):
    if base == "traffic":
        if unit == "bit/s" and stat == "mean":
            return "identity"
        if unit == "byte/s" and stat == "mean":
            return "bytesps_to_bps"
        if unit == "byte" and stat in {"sum", "delta_sum"}:
            return "bytes_to_bps"
    if base in {"packets", "drops"}:
        if unit == "packet/s" and stat == "mean":
            return "identity"
        if unit in {"packet", "count"} and stat in {"sum", "delta_sum"}:
            return "count_to_pps"
    if base == "optical" and (unit, stat) == ("dBm", "sample"):
        return "identity"
    if base == "peak_util" and (unit, stat) == ("percent", "max"):
        return "percent_to_fraction"
    if base == "capacity" and stat == "sample":
        return {"byte/s": "bytesps_to_bps", "bit/s": "identity"}.get(unit)
    return None

def rule_proposal(row, customer_perspective=False):
    name = words(row.metric)
    description = words(row.definition)
    terms = name | description
    if terms & {"unicast", "multicast", "broadcast", "mismatch", "nat", "errors", "state", "established"}:
        return "OUT", "none"
    if any(phrase in row.definition.lower() for phrase in ["because of link congestion", "attributable to"]):
        return "OUT", "none"

    if terms & {"capacity"}:
        base = "capacity"
    elif terms & {"discard", "discards", "discarded", "drop", "drops", "dropped"}:
        base = "drops"
    elif row.unit == "dBm":
        base = "optical"
    elif terms & {"utilization", "utilisation"}:
        base = "peak_util"
    elif terms & {"packets", "packet", "pps"}:
        base = "packets"
    elif row.unit in {"bit/s", "byte/s", "byte"}:
        base = "traffic"
    else:
        return "OUT", "none"

    op = choose_op(base, row.unit, row.stat)
    if not op:
        return "OUT", "none"
    if base == "capacity":
        return base, op

    # Ignore bare "in" and "out" as isolated prepositions in a description.
    directions = {d for d, keys in DIRECTION_WORDS.items()
                  if (name & keys) or (description & (keys - {"in", "out"}))}
    if customer_perspective:
        if re.search(r"\b(?:sent|transmitted) to (?:the )?customer\b", row.definition, re.I):
            directions = {"out"}
        elif re.search(r"\breceived from (?:the )?customer\b", row.definition, re.I):
            directions = {"in"}
    if len(directions) == 1:
        return f"{base}_{next(iter(directions))}", op
    return ("REVIEW", "none") if directions else ("OUT", "none")

