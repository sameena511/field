def choose_op(base, unit, stat):
    if base == "traffic":
        if unit == "bit/s" and stat == "mean":
            return "identity"
        if unit == "byte/s" and stat == "mean":
            return "bytesps_to_bps"
        if unit == "byte" and stat in {"sum", "delta_sum"}:
            return "bytes_to_bps"
    if base in {"packets", "drops"}:
        if unit == "packet/s" and stat == "mean":
            return "identity"
        if unit in {"packet", "count"} and stat in {"sum", "delta_sum"}:
            return "count_to_pps"
    if base == "optical" and (unit, stat) == ("dBm", "sample"):
        return "identity"
    if base == "peak_util" and (unit, stat) == ("percent", "max"):
        return "percent_to_fraction"
