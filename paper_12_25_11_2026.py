def review_endpoint_directions(proposals):
    checked = validate_map(proposals)[["rid", "target", "op"]].copy().set_index("rid")
    for row in endpoint_rows.itertuples(index=False):
        # The augmented parser reads provider direction and checks the unit and statistic.
        # Parse the definition without using a reference label or the other method's proposal.
        target, op = rule_proposal(row, customer_perspective=True)
        if target in catalog:
            checked.loc[row.rid, ["target", "op"]] = [target, op]
    return checked.reset_index()

def canonical_report(mapping):
    table = build_report(mapping, case).rename(columns={"source": "rid"})
    table["canonical_unit"] = table.target.map(lambda target: catalog[target]["canonical_unit"])
    return table.sort_values(key).reset_index(drop=True)

